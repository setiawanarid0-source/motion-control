import fs from 'node:fs';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';

// Keep both execution channels on the same exporter and import format.
export function buildRunningHubUserscript(){
  const context={window:{}};
  vm.runInNewContext(fs.readFileSync(new URL('../public/rh-session.js',import.meta.url),'utf8'),context);
  return `// ==UserScript==
// @name         Vanta · Salin sesi RunningHub
// @namespace    https://github.com/setiawanarid0-source/motion-control
// @version      2026.11.13.1
// @description  Tampilkan sesi RunningHub hanya saat tombol Salin sesi ke Vanta ditekan. Tidak mengirim data.
// @match        https://www.runninghub.ai/*
// @match        https://runninghub.ai/*
// @run-at       document-idle
// @sandbox      DOM
// @noframes
// @downloadURL  none
// ==/UserScript==

// Generated by scripts/build-rh-session-userscript.mjs. No GM privileges or page globals needed.
(function(){
  'use strict';
  if(location.protocol!=='https:'||!/^(www\\.)?runninghub\\.ai$/i.test(location.hostname)||window.top!==window.self)return;
  if(document.getElementById('vanta-rh-session-launcher'))return;
  ${context.exportRunningHubSession.toString()}
  var button=document.createElement('button');
  button.id='vanta-rh-session-launcher';button.type='button';button.textContent='Salin sesi ke Vanta';
  button.style.cssText='position:fixed;right:16px;bottom:calc(16px + env(safe-area-inset-bottom,0px));z-index:2147483646;max-width:calc(100vw - 32px);min-height:44px;padding:12px 16px;border:1px solid #343b49;border-radius:12px;background:#b4ff54;color:#111;font:600 16px system-ui,sans-serif;cursor:pointer';
  button.onclick=exportRunningHubSession;
  (document.body||document.documentElement).appendChild(button);
})();
`;
}

if(process.argv[1]===fileURLToPath(import.meta.url)){
  fs.writeFileSync(new URL('../public/vanta-runninghub-session.user.js',import.meta.url),buildRunningHubUserscript());
}
